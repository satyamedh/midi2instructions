const size_t NUM_EVENTS = sizeof(midi_events) / sizeof(midi_events[0]);

void setup() {
  pinMode(12, OUTPUT);
}

void loop() {
  for (size_t i = 0; i < NUM_EVENTS; i++) {
    uint32_t event = midi_events[i];

    // upper 16 are freq
    uint16_t freq = event >> 16;

    // lower 16 are time in ms
    uint16_t dur_ms = event & 0xFFFF;

    if (freq == 0) {
      // pause
      noTone(12);
    } else {
      tone(12, freq);
    }
    delay(dur_ms);
    noTone(12);

  }

  delay(1000);

}
